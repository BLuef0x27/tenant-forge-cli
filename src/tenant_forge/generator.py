"""Tenant input validation and Terraform variable file generation."""

from __future__ import annotations

import ipaddress
import re
from pathlib import Path

TENANT_ID_PATTERN = re.compile(r"^[a-z0-9-]+$")
VALID_ENVIRONMENTS = ("staging", "prod")
MIN_PREFIXLEN = 16
MAX_PREFIXLEN = 24


def validate_tenant_id(tenant_id: str) -> str:
    """Normalize and validate a tenant identifier.

    The value is stripped of surrounding whitespace and lowercased, then
    checked against ``^[a-z0-9-]+$`` so it is safe to embed in AWS
    resource names, tags, and Terraform variable files.

    Raises:
        ValueError: if the normalized value contains anything other than
            lowercase letters, digits, and hyphens.
    """
    clean = tenant_id.strip().lower()
    if not TENANT_ID_PATTERN.match(clean):
        raise ValueError(
            "tenant_id must contain only lowercase letters, digits, and "
            f"hyphens after normalization; got {tenant_id!r}"
        )
    return clean


def validate_cidr(vpc_cidr: str) -> str:
    """Validate a VPC CIDR block for tenant allocation.

    The value must parse as a strict CIDR network and its prefix length
    must fall between /16 and /24 inclusive, which bounds the size of any
    single tenant footprint.

    Raises:
        ValueError: if the CIDR is malformed or outside the supported
            prefix range.
    """
    try:
        network = ipaddress.ip_network(vpc_cidr, strict=True)
    except ValueError as exc:
        raise ValueError(
            f"vpc_cidr is not a valid CIDR block: {vpc_cidr!r} ({exc})"
        ) from exc
    if not (MIN_PREFIXLEN <= network.prefixlen <= MAX_PREFIXLEN):
        raise ValueError(
            "vpc_cidr prefix must be between /16 and /24 inclusive; got "
            f"/{network.prefixlen} ({vpc_cidr!r})"
        )
    return str(network)


def validate_environment(environment: str) -> str:
    """Normalize and validate the deployment environment.

    Raises:
        ValueError: if the environment is not ``staging`` or ``prod``.
    """
    clean = environment.strip().lower()
    if clean not in VALID_ENVIRONMENTS:
        raise ValueError(
            f"environment must be one of {VALID_ENVIRONMENTS}; got {environment!r}"
        )
    return clean


def write_tfvars(
    tenant_id: str,
    environment: str,
    vpc_cidr: str,
    output_dir: Path = Path("tenants"),
) -> Path:
    """Validate tenant inputs and write a Terraform variable file.

    Args:
        tenant_id: tenant identifier; normalized then validated.
        environment: target environment; must be ``staging`` or ``prod``.
        vpc_cidr: VPC CIDR block between /16 and /24 inclusive.
        output_dir: directory that receives the generated file.

    Returns:
        The path of the written ``.tfvars`` file, named
        ``{tenant_id}-{environment}.tfvars``.

    Raises:
        ValueError: if any input fails validation. Nothing is written in
            that case.
    """
    clean_id = validate_tenant_id(tenant_id)
    clean_env = validate_environment(environment)
    clean_cidr = validate_cidr(vpc_cidr)

    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    tfvars_path = output_dir / f"{clean_id}-{clean_env}.tfvars"
    tfvars_path.write_text(
        "# Generated by TenantForge; review before applying.\n"
        f'tenant_id   = "{clean_id}"\n'
        f'environment = "{clean_env}"\n'
        f'vpc_cidr    = "{clean_cidr}"\n',
        encoding="utf-8",
    )
    return tfvars_path
